export function findRoomAndRate(roomId?: string | null, rateId?: string | null) {
  const room = rooms.find((item) => item.id === roomId) ?? rooms[0]
  const rate = room.rates.find((item) => item.id === rateId) ?? room.rates[0]
  return { room, rate }
}

export function rateTotal(rate: RatePlan) {
  return rate.room + rate.taxes
}
